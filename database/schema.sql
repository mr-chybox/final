-- =============================================================
-- 5. USERS TABLE (customer accounts)
-- =============================================================
CREATE TABLE IF NOT EXISTS users (
    id              SERIAL          PRIMARY KEY,

    -- Full name (Bengali or English)
    full_name       VARCHAR(200)    NOT NULL,

    -- Unique email — used as login identifier
    email           VARCHAR(255)    NOT NULL UNIQUE,

    -- bcrypt-hashed password (never store plain text)
    password_hash   TEXT            NOT NULL,

    -- Optional profile fields
    phone           VARCHAR(20),
    address         TEXT,
    district        VARCHAR(100),
    thana           VARCHAR(100),

    -- Account status
    is_active       BOOLEAN         NOT NULL DEFAULT TRUE,
    is_verified     BOOLEAN         NOT NULL DEFAULT FALSE,

    -- Audit timestamps
    created_at      TIMESTAMPTZ     NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ     NOT NULL DEFAULT NOW(),
    last_login_at   TIMESTAMPTZ
);

-- Indexes
CREATE INDEX IF NOT EXISTS idx_users_email     ON users (email);
CREATE INDEX IF NOT EXISTS idx_users_phone     ON users (phone);
CREATE INDEX IF NOT EXISTS idx_users_is_active ON users (is_active);

-- Auto-update trigger
DROP TRIGGER IF EXISTS set_updated_at_users ON users;
CREATE TRIGGER set_updated_at_users
    BEFORE UPDATE ON users
    FOR EACH ROW EXECUTE FUNCTION trigger_set_updated_at();

-- =============================================================
-- 6. Link orders → users (optional FK, SET NULL on delete)
-- =============================================================
-- Add user_id to orders if it doesn't exist yet
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_name='orders' AND column_name='user_id'
  ) THEN
    ALTER TABLE orders ADD COLUMN user_id INTEGER REFERENCES users(id) ON DELETE SET NULL;
    CREATE INDEX idx_orders_user_id ON orders(user_id);
  END IF;
END $$;
