-- ─────────────────────────────────────────────────────────────
-- 0. EXTENSIONS
-- ─────────────────────────────────────────────────────────────
-- pgcrypto gives us gen_random_uuid() for UUID primary keys.
CREATE EXTENSION IF NOT EXISTS "pgcrypto";


-- ─────────────────────────────────────────────────────────────
-- 1. PRODUCTS TABLE
-- ─────────────────────────────────────────────────────────────
-- Stores the product catalogue that the storefront renders.
-- ─────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS products (
    id          SERIAL          PRIMARY KEY,

    -- Bengali product name shown on the frontend
    name        VARCHAR(200)    NOT NULL,

    -- Optional English / transliterated name for search / SEO
    name_en     VARCHAR(200),

    -- Price in BDT (Bangladeshi Taka). Stored as NUMERIC to avoid
    -- floating-point rounding issues.
    price       NUMERIC(10, 2)  NOT NULL CHECK (price >= 0),

    -- Unit label displayed next to the price, e.g. "লিটার", "কেজি"
    unit        VARCHAR(50)     NOT NULL DEFAULT 'পিস',

    -- Relative path to the product image served from /public
    image       TEXT            NOT NULL DEFAULT './assets/images/products/placeholder.jpg',

    -- Alt text for accessibility / SEO (Bengali)
    alt_text    TEXT,

    -- Category used for filter tabs on the frontend
    -- e.g. 'তেল', 'মশলা', 'চিনি', 'মধু', 'চাল'
    category    VARCHAR(100),

    -- Optional badge label rendered on the card, e.g. 'নতুন', 'বেস্টসেলার'
    badge       VARCHAR(50),

    -- Controls whether the "অর্ডার করুন" button is active
    in_stock    BOOLEAN         NOT NULL DEFAULT TRUE,

    -- Audit timestamps (auto-managed)
    created_at  TIMESTAMPTZ     NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMPTZ     NOT NULL DEFAULT NOW()
);

-- Index for common filter queries (?category=তেল)
CREATE INDEX IF NOT EXISTS idx_products_category ON products (category);
CREATE INDEX IF NOT EXISTS idx_products_in_stock  ON products (in_stock);


-- ─────────────────────────────────────────────────────────────
-- 2. ORDERS TABLE
-- ─────────────────────────────────────────────────────────────
-- Each row represents one product line in a customer's order.
-- A cart with 3 products will INSERT 3 rows sharing an order_ref.
-- ─────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS orders (
    id              SERIAL          PRIMARY KEY,

    -- Human-readable order reference, e.g. "PB-1712345678901"
    -- Generated by the application before insert.
    order_ref       VARCHAR(30)     NOT NULL,

    -- FK to the products table. SET NULL on product deletion so
    -- historical orders are never lost.
    product_id      INTEGER         REFERENCES products (id) ON DELETE SET NULL,

    -- Snapshot of the product name at order time (in case product
    -- is later renamed or deleted).
    product_name    VARCHAR(200)    NOT NULL,

    -- How many units the customer ordered
    quantity        INTEGER         NOT NULL CHECK (quantity > 0),

    -- Unit price snapshot at the time of ordering
    unit_price      NUMERIC(10, 2)  NOT NULL CHECK (unit_price >= 0),

    -- Computed total: quantity × unit_price (stored for reporting)
    total_price     NUMERIC(12, 2)  GENERATED ALWAYS AS (quantity * unit_price) STORED,

    -- Customer details
    customer_name   VARCHAR(200)    NOT NULL,
    phone           VARCHAR(20)     NOT NULL,
    address         TEXT            NOT NULL,

    -- Order lifecycle status
    -- pending → confirmed → shipped → delivered | cancelled
    status          VARCHAR(20)     NOT NULL DEFAULT 'pending'
                        CHECK (status IN ('pending','confirmed','shipped','delivered','cancelled')),

    -- Optional note from the admin
    admin_note      TEXT,

    -- Audit timestamps
    created_at      TIMESTAMPTZ     NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ     NOT NULL DEFAULT NOW()
);

-- Indexes for admin dashboard queries
CREATE INDEX IF NOT EXISTS idx_orders_order_ref   ON orders (order_ref);
CREATE INDEX IF NOT EXISTS idx_orders_status      ON orders (status);
CREATE INDEX IF NOT EXISTS idx_orders_created_at  ON orders (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_orders_phone       ON orders (phone);


-- ─────────────────────────────────────────────────────────────
-- 3. AUTO-UPDATE updated_at TRIGGER
-- ─────────────────────────────────────────────────────────────
-- Keeps updated_at in sync automatically on every UPDATE.

CREATE OR REPLACE FUNCTION trigger_set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Attach to products
DROP TRIGGER IF EXISTS set_updated_at_products ON products;
CREATE TRIGGER set_updated_at_products
    BEFORE UPDATE ON products
    FOR EACH ROW EXECUTE FUNCTION trigger_set_updated_at();

-- Attach to orders
DROP TRIGGER IF EXISTS set_updated_at_orders ON orders;
CREATE TRIGGER set_updated_at_orders
    BEFORE UPDATE ON orders
    FOR EACH ROW EXECUTE FUNCTION trigger_set_updated_at();


